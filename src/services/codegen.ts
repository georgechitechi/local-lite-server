import fs from 'node:fs';
import path from 'node:path';
import type { FunctionRegistry } from '../functions/index.js';
import type { SchemaDictionary, SchemaFieldType } from '../db/schema.js';

function tsType(field: SchemaFieldType): string {
  const nullable = field.endsWith(' | null');
  const base = nullable ? field.slice(0, -' | null'.length) : field;
  const mapped =
    base === 'string'
      ? 'string'
      : base === 'number'
        ? 'number'
        : base === 'boolean'
          ? 'boolean'
          : base === 'string[]'
            ? 'string[]'
            : 'Record<string, unknown>';
  return nullable ? `${mapped} | null` : mapped;
}

function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

export function generateClientCode(schema: SchemaDictionary, functions: FunctionRegistry): string {
  const lines: string[] = [
    '// Auto-generated by `local-lite-server codegen`. Do not edit by hand.',
    '',
    'export interface ClientOptions {',
    '  url: string;',
    '  getToken?: () => string | null | undefined | Promise<string | null | undefined>;',
    '  fetch?: typeof fetch;',
    '}',
    '',
  ];

  for (const [table, fields] of Object.entries(schema)) {
    lines.push(`export interface ${pascal(table)}Row {`);
    for (const [col, t] of Object.entries(fields)) {
      lines.push(`  ${col}: ${tsType(t)};`);
    }
    if (!fields.updated_at) lines.push('  updated_at: number;');
    if (!fields.deleted) lines.push('  deleted: boolean;');
    lines.push('}', '');
  }

  const byMod = new Map<string, Array<{ name: string; kind: string }>>();
  for (const [full, def] of functions.entries()) {
    const [mod, fn] = full.split('/');
    if (!mod || !fn) continue;
    const list = byMod.get(mod) ?? [];
    list.push({ name: fn, kind: def.__kind });
    byMod.set(mod, list);
  }

  lines.push(
    'export function createClient(opts: ClientOptions) {',
    '  const baseUrl = opts.url.replace(/\\/+$/, "");',
    '  const doFetch = opts.fetch ?? globalThis.fetch;',
    '',
    '  async function call<T = unknown>(fn: string, args: Record<string, unknown> = {}): Promise<T> {',
    '    const token = await opts.getToken?.();',
    '    const headers: Record<string, string> = { "Content-Type": "application/json" };',
    '    if (token) headers.Authorization = `Bearer ${token}`;',
    '    const res = await doFetch(`${baseUrl}/fn/${fn}`, {',
    '      method: "POST",',
    '      headers,',
    '      body: JSON.stringify({ args }),',
    '    });',
    '    const data = (await res.json().catch(() => ({}))) as { result?: T; error?: string };',
    '    if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);',
    '    return data.result as T;',
    '  }',
    '',
    '  function subscribe<T = unknown>(',
    '    fn: string,',
    '    args: Record<string, unknown>,',
    '    onData: (data: T) => void,',
    '    onError?: (err: unknown) => void,',
    '  ): () => void {',
    '    let es: EventSource | null = null;',
    '    let closed = false;',
    '    void Promise.resolve(opts.getToken?.()).then((token) => {',
    '      if (closed) return;',
    '      const q = new URLSearchParams({ args: JSON.stringify(args) });',
    '      if (token) q.set("token", token);',
    '      es = new EventSource(`${baseUrl}/subscribe/${fn}?${q.toString()}`);',
    '      es.addEventListener("data", (ev) => {',
    '        try { onData(JSON.parse((ev as MessageEvent).data) as T); } catch (e) { onError?.(e); }',
    '      });',
    '      if (onError) es.addEventListener("error", onError);',
    '    });',
    '    return () => { closed = true; es?.close(); };',
    '  }',
    '',
    '  return {',
    '    call,',
    '    subscribe,',
  );

  for (const [mod, fns] of byMod) {
    lines.push(`    ${mod}: {`);
    for (const f of fns) {
      lines.push(
        `      ${f.name}: <T = unknown>(args: Record<string, unknown> = {}) => call<T>("${mod}/${f.name}", args),`,
      );
      if (f.kind === 'query') {
        lines.push(
          `      subscribe${pascal(f.name)}: <T = unknown>(args: Record<string, unknown>, onData: (data: T) => void, onError?: (err: unknown) => void) => subscribe<T>("${mod}/${f.name}", args, onData, onError),`,
        );
      }
    }
    lines.push('    },');
  }

  lines.push('  };', '}', '');
  return lines.join('\n');
}

export function writeClientCode(
  outFile: string,
  schema: SchemaDictionary,
  functions: FunctionRegistry,
): string {
  const abs = path.resolve(process.cwd(), outFile);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, generateClientCode(schema, functions));
  return abs;
}
