import fs from 'node:fs';
import path from 'node:path';
import type { CommandRegistry } from '../commands/index.js';
import type { LensRegistry } from '../db/lenses.js';
import type { SchemaDictionary, SchemaFieldType } from '../db/schema.js';

function tsType(field: SchemaFieldType): string {
  const nullable = field.endsWith(' | null');
  const base = nullable ? field.slice(0, -' | null'.length) : field;
  const mapped =
    base === 'string'
      ? 'string'
      : base === 'number'
        ? 'number'
        : base === 'boolean'
          ? 'boolean'
          : base === 'string[]'
            ? 'string[]'
            : 'Record<string, unknown>';
  return nullable ? `${mapped} | null` : mapped;
}

function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

export function generateClientCode(
  schema: SchemaDictionary,
  commands: CommandRegistry = new Map(),
  lenses: LensRegistry = new Map(),
): string {
  const lines: string[] = [
    '// Auto-generated by `local-lite-server codegen`. Do not edit by hand.',
    '',
    'export interface ClientOptions {',
    '  url: string;',
    '  getToken?: () => string | null | undefined | Promise<string | null | undefined>;',
    '  fetch?: typeof fetch;',
    '}',
    '',
    'export interface CommandRunOptions {',
    '  idempotencyKey?: string;',
    '}',
    '',
    'export interface CommandResult<T = unknown> {',
    '  success: boolean;',
    '  result?: T;',
    '  checkpoint?: number;',
    '  rejected?: boolean;',
    '  code?: string;',
    '  error?: string;',
    '  details?: unknown;',
    '  deduplicated?: boolean;',
    '}',
    '',
  ];

  for (const [table, fields] of Object.entries(schema)) {
    lines.push(`export interface ${pascal(table)}Row {`);
    for (const [col, t] of Object.entries(fields)) {
      lines.push(`  ${col}: ${tsType(t)};`);
    }
    if (!fields.updated_at) lines.push('  updated_at: number;');
    if (!fields.deleted) lines.push('  deleted: boolean;');
    lines.push('}', '');
  }

  const byMod = new Map<string, string[]>();
  for (const [full] of commands.entries()) {
    const [mod, cmd] = full.split('/');
    if (!mod || !cmd) continue;
    const list = byMod.get(mod) ?? [];
    list.push(cmd);
    byMod.set(mod, list);
  }

  lines.push(
    'export function createClient(opts: ClientOptions) {',
    '  const baseUrl = opts.url.replace(/\\/+$/, "");',
    '  const doFetch = opts.fetch ?? globalThis.fetch;',
    '',
    '  async function runCommand<T = unknown>(',
    '    cmd: string,',
    '    args: Record<string, unknown> = {},',
    '    cmdOpts: CommandRunOptions = {},',
    '  ): Promise<CommandResult<T>> {',
    '    const token = await opts.getToken?.();',
    '    const headers: Record<string, string> = { "Content-Type": "application/json" };',
    '    if (token) headers.Authorization = `Bearer ${token}`;',
    '    if (cmdOpts.idempotencyKey) headers["Idempotency-Key"] = cmdOpts.idempotencyKey;',
    '    const res = await doFetch(`${baseUrl}/cmd/${cmd}`, {',
    '      method: "POST",',
    '      headers,',
    '      body: JSON.stringify({ args }),',
    '    });',
    '    const data = (await res.json().catch(() => ({}))) as CommandResult<T>;',
    '    if (!res.ok && !data.rejected) throw new Error(data.error || `Request failed (${res.status})`);',
    '    return data;',
    '  }',
    '',
    '  async function pullLens<T = Record<string, unknown>>(',
    '    lens: string,',
    '    args: Record<string, unknown> = {},',
    '    since = 0,',
    '  ) {',
    '    const token = await opts.getToken?.();',
    '    const headers: Record<string, string> = {};',
    '    if (token) headers.Authorization = `Bearer ${token}`;',
    '    const q = new URLSearchParams({ since: String(since), args: JSON.stringify(args) });',
    '    const res = await doFetch(`${baseUrl}/sync/lens/${lens}?${q.toString()}`, { headers });',
    '    const data = (await res.json().catch(() => ({}))) as any;',
    '    if (!res.ok) throw new Error(data.error || `Lens pull failed (${res.status})`);',
    '    return data as { cursor: number; hasMore: boolean; changes: { timestamp: number; changes: T[] } };',
    '  }',
    '',
    '  async function snapshotLens<T = Record<string, unknown>>(',
    '    lens: string,',
    '    args: Record<string, unknown> = {},',
    '  ) {',
    '    const token = await opts.getToken?.();',
    '    const headers: Record<string, string> = {};',
    '    if (token) headers.Authorization = `Bearer ${token}`;',
    '    const q = new URLSearchParams({ format: "json", args: JSON.stringify(args) });',
    '    const res = await doFetch(`${baseUrl}/sync/snapshot/${lens}?${q.toString()}`, { headers });',
    '    const data = (await res.json().catch(() => ({}))) as any;',
    '    if (!res.ok) throw new Error(data.error || `Snapshot failed (${res.status})`);',
    '    return data as { checkpoint: number; rows: T[] };',
    '  }',
    '',
    '  function subscribeLens<T = unknown>(',
    '    lens: string,',
    '    args: Record<string, unknown>,',
    '    onDeltas: (data: T) => void,',
    '    onError?: (err: unknown) => void,',
    '    since = 0,',
    '  ): () => void {',
    '    let es: EventSource | null = null;',
    '    let closed = false;',
    '    void Promise.resolve(opts.getToken?.()).then((token) => {',
    '      if (closed) return;',
    '      const q = new URLSearchParams({ since: String(since), args: JSON.stringify(args) });',
    '      if (token) q.set("token", token);',
    '      es = new EventSource(`${baseUrl}/sync/lens/${lens}/events?${q.toString()}`);',
    '      es.addEventListener("deltas", (ev) => {',
    '        try { onDeltas(JSON.parse((ev as MessageEvent).data) as T); } catch (e) { onError?.(e); }',
    '      });',
    '      if (onError) es.addEventListener("error", onError);',
    '    });',
    '    return () => { closed = true; es?.close(); };',
    '  }',
    '',
    '  return {',
    '    runCommand,',
    '    pullLens,',
    '    snapshotLens,',
    '    subscribeLens,',
  );

  for (const [mod, cmds] of byMod) {
    lines.push(`    ${mod}: {`);
    for (const c of cmds) {
      lines.push(
        `      ${c}: <T = unknown>(args: Record<string, unknown> = {}, cmdOpts?: CommandRunOptions) => runCommand<T>("${mod}/${c}", args, cmdOpts),`,
      );
    }
    lines.push('    },');
  }

  if (lenses.size > 0) {
    lines.push('    lenses: {');
    for (const [name] of lenses) {
      lines.push(`      ${name}: {`);
      lines.push(
        `        pull: <T = Record<string, unknown>>(args: Record<string, unknown> = {}, since = 0) => pullLens<T>("${name}", args, since),`,
      );
      lines.push(
        `        snapshot: <T = Record<string, unknown>>(args: Record<string, unknown> = {}) => snapshotLens<T>("${name}", args),`,
      );
      lines.push(
        `        subscribe: <T = unknown>(args: Record<string, unknown>, onDeltas: (data: T) => void, onError?: (err: unknown) => void, since = 0) => subscribeLens<T>("${name}", args, onDeltas, onError, since),`,
      );
      lines.push('      },');
    }
    lines.push('    },');
  }

  lines.push('  };', '}', '');
  return lines.join('\n');
}

export function writeClientCode(
  outFile: string,
  schema: SchemaDictionary,
  commands: CommandRegistry = new Map(),
  lenses: LensRegistry = new Map(),
): string {
  const abs = path.resolve(process.cwd(), outFile);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, generateClientCode(schema, commands, lenses));
  return abs;
}
